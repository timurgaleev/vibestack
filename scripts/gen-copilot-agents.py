#!/usr/bin/env python3
"""Build copilot/agents/*.agent.md from claude/agents/*.md.

Copilot CLI reads custom agents from ~/.copilot/agents/<id>.agent.md, where the
id is the filename. Its frontmatter takes `description` (required), `name` and
`tools`, and accepts Claude's tool names as aliases, so the Claude agents carry
over with three changes:

- `model` is dropped: Claude tier names (opus, sonnet) are not Copilot model ids.
- `tools` becomes a flow list, the shape Copilot documents.
- `description` is written as a quoted scalar, so a colon in the text cannot
  turn into a YAML key.

The body is copied verbatim and must stay within Copilot's 30,000-character
limit.

    ./scripts/gen-copilot-agents.py            # write copilot/agents/
    ./scripts/gen-copilot-agents.py --check    # exit 1 if any file is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "config" / "claude" / "agents"
OUT = ROOT / "config" / "copilot" / "agents"

# The directory's index, not an agent.
SKIP = {"README.md"}

BODY_LIMIT = 30000

HEADER = ("<!-- Generated by scripts/gen-copilot-agents.py from claude/agents/. "
          "Do not edit directly — edit the source and regenerate. -->\n\n")


class AgentError(Exception):
    pass


def parse(path: Path) -> tuple[dict[str, str], str]:
    """Split a Claude agent into its flat `key: value` frontmatter and body."""
    text = path.read_text()
    if not text.startswith("---\n"):
        raise AgentError(f"{path.name}: no frontmatter")
    head, sep, body = text[4:].partition("\n---\n")
    if not sep:
        raise AgentError(f"{path.name}: unterminated frontmatter")
    meta: dict[str, str] = {}
    for line in head.splitlines():
        if not line.strip():
            continue
        key, colon, value = line.partition(":")
        if not colon or line[:1].isspace():
            raise AgentError(f"{path.name}: unsupported frontmatter line {line!r}")
        meta[key.strip()] = value.strip()
    return meta, body


def render(path: Path) -> str:
    meta, body = parse(path)
    agent_id = path.name[: -len(".md")]
    if meta.get("name") != agent_id:
        raise AgentError(f"{path.name}: name {meta.get('name')!r} does not match the filename")
    if not meta.get("description"):
        raise AgentError(f"{path.name}: no description")
    body = HEADER + body.lstrip("\n")
    if len(body) > BODY_LIMIT:
        raise AgentError(f"{path.name}: body is {len(body)} chars, Copilot allows {BODY_LIMIT}")

    lines = ["---", f"name: {agent_id}",
             f"description: {json.dumps(meta['description'], ensure_ascii=False)}"]
    if meta.get("tools"):
        tools = [t.strip() for t in meta["tools"].split(",") if t.strip()]
        lines.append(f"tools: {json.dumps(tools)}")
    lines.append("---")
    return "\n".join(lines) + "\n" + body


def build() -> dict[str, str]:
    return {
        f"{p.name[: -len('.md')]}.agent.md": render(p)
        for p in sorted(SRC.glob("*.md"))
        if p.name not in SKIP
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if copilot/agents differs from the generated output")
    args = parser.parse_args()

    try:
        generated = build()
    except AgentError as exc:
        print(f"gen-copilot-agents: {exc}", file=sys.stderr)
        return 1

    existing = {p.name for p in OUT.glob("*.agent.md")} if OUT.is_dir() else set()

    if args.check:
        stale = sorted(n for n, text in generated.items()
                       if not (OUT / n).is_file() or (OUT / n).read_text() != text)
        extra = sorted(existing - set(generated))
        if not stale and not extra:
            print(f"copilot/agents is up to date ({len(generated)} agents)")
            return 0
        for name in stale:
            print(f"stale: {name}", file=sys.stderr)
        for name in extra:
            print(f"no source: {name}", file=sys.stderr)
        print("copilot/agents is out of date — run scripts/gen-copilot-agents.py",
              file=sys.stderr)
        return 1

    OUT.mkdir(parents=True, exist_ok=True)
    for name in existing - set(generated):
        (OUT / name).unlink()
    for name, text in generated.items():
        (OUT / name).write_text(text)
    print(f"wrote {len(generated)} agents to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
